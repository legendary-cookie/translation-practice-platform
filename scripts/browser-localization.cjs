const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright-core')
const output = path.resolve(process.env.BROWSER_QA_ARTIFACTS || '.browser-qa')
fs.mkdirSync(output, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ channel: process.env.QA_BROWSER_CHANNEL || 'chrome', headless: true })
  const checks = [], errors = [], posts = []
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true })
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.method() === 'POST') posts.push(request.url()) })
    const nav = name => page.getByRole('navigation').filter({ visible: true }).getByRole('button', { name, exact: true }).click()
    const pass = text => { checks.push(text); console.log('PASS', text) }
    await page.goto('http://127.0.0.1:4178')
    await nav('Practice')
    await page.getByRole('button', { name: 'Open translation desk' }).click()
    const source = await page.locator('.source-text').innerText()
    const answer = 'Verbatim learner text 中文 العربية हिन्दी <b>not markup</b>'
    await page.locator('#translation-answer').fill(answer)
    await page.getByText('Draft saved on this device', { exact: false }).waitFor()
    await nav('Settings')
    await page.locator('#interface-language').selectOption('zh-CN')
    await page.getByRole('heading', { name: '清楚了解数据边界。' }).waitFor()
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN')
    await page.getByRole('combobox', { name: '学习目标', exact: true }).selectOption('CATTI preparation')
    await page.reload()
    await nav('设置')
    assert.equal(await page.locator('#interface-language').inputValue(), 'zh-CN')
    assert.equal(await page.getByRole('combobox', { name: '学习目标', exact: true }).inputValue(), 'CATTI preparation')
    pass('Chinese interface language and stable preference values persist after reload')
    await page.screenshot({ path: path.join(output, 'settings-390-chinese.png'), fullPage: true })
    await nav('首页')
    await page.getByRole('button', { name: '继续翻译' }).click()
    await page.getByRole('button', { name: '编写译文', exact: true }).click()
    assert.equal(await page.locator('#translation-answer').inputValue(), answer)
    assert.equal(await page.locator('.source-text').innerText(), source)
    pass('Changing interface language preserves exact authored source and learner answer')
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 })
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    }
    await page.screenshot({ path: path.join(output, 'desk-1440-chinese.png'), fullPage: true })
    pass('Chinese workspace reflows at four phone/tablet/desktop widths')
    await nav('考试')
    await page.getByRole('button', { name: '开始模拟考试' }).first().waitFor()
    await page.getByRole('button', { name: '开始模拟考试' }).first().click()
    await page.locator('#exam-answer-input').fill('考试原样保留 test')
    await page.evaluate(() => window.dispatchEvent(new Event('lingo-native-back', { cancelable: true })))
    await page.getByRole('button', { name: /继续考试/ }).waitFor()
    pass('Native Back saves the exam through the existing fenced save-and-exit path')
    await nav('口译')
    await page.getByRole('button', { name: '打开口译练习区' }).waitFor()
    await nav('进度')
    await page.getByRole('heading', { name: '把有用的表达留在身边。' }).waitFor()
    await nav('设置')
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出本地 JSON', exact: true }).click()
    const file = await download
    const archive = JSON.parse(fs.readFileSync(await file.path(), 'utf8'))
    assert.equal(archive.workspacePreferences.interfaceLanguage, 'zh-CN')
    assert.equal(archive.writtenDraft.answer, answer)
    await page.locator('#interface-language').selectOption('en')
    await page.getByRole('heading', { name: 'Make the boundary visible.' }).waitFor()
    pass('Localized core routes and JSON export work; language can be switched back to English')
    assert.deepEqual(errors, [])
    assert.deepEqual(posts, [])
    pass('Localization sends no network content and produces no page errors')
    await context.close()
  } catch (error) { console.error(error); process.exitCode = 1; checks.push(`FAIL: ${error.message}`) }
  finally { fs.writeFileSync(path.join(output, 'localization-results.json'), JSON.stringify({ checks, errors, posts }, null, 2)); await browser.close() }
})()
