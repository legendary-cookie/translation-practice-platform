const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const { chromium } = require('playwright-core')
const sdk = process.env.ANDROID_HOME || path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk')
const adbPath = path.join(sdk, 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb')
const serial = process.env.ANDROID_QA_SERIAL
if (!serial || !serial.startsWith('emulator-')) throw new Error('Set ANDROID_QA_SERIAL to an isolated QA emulator. Never run this against a learner device.')
const app = 'com.legendarycookie.lingopractice'
const adb = (...args) => execFileSync(adbPath, ['-s', serial, ...args], { encoding: 'utf8' }).trim()
const output = path.resolve('.browser-qa')
fs.mkdirSync(output, { recursive: true })
const report = { serial, checks: [], errors: [], posts: [] }
const pass = name => { report.checks.push(name); console.log('PASS', name) }
let browser, page
async function connect() {
  const pid = adb('shell', 'pidof', app)
  adb('forward', 'tcp:9224', `localabstract:webview_devtools_remote_${pid}`)
  browser = await chromium.connectOverCDP('http://127.0.0.1:9224', { noDefaults: true })
  page = browser.contexts()[0].pages()[0]
  page.on('dialog', dialog => dialog.accept())
  page.on('pageerror', error => report.errors.push(error.message))
  page.on('request', request => { if (request.method() === 'POST') report.posts.push(request.url()) })
}
const nav = name => page.getByRole('navigation').filter({ visible: true }).getByRole('button', { name, exact: true }).click()
const back = () => adb('shell', 'input', 'keyevent', '4')
async function hideKeyboard() {
  if (adb('shell', 'dumpsys', 'input_method').includes('mInputShown=true')) {
    back()
    await page.waitForTimeout(400)
  }
  await page.locator('textarea:focus,input:focus').evaluateAll(elements => elements.forEach(element => element.blur()))
}
;(async () => {
  try {
    // Only this isolated QA emulator is affected, including its synthetic microphone permission.
    adb('shell', 'pm', 'grant', app, 'android.permission.RECORD_AUDIO')
    await connect()
    if (await page.locator('#interface-language').count()) await page.locator('#interface-language').selectOption('en')
    if (await page.getByRole('button', { name: 'Explore first', exact: true }).count()) await page.getByRole('button', { name: 'Explore first', exact: true }).click()
    await nav('Practice')
    await page.getByRole('button', { name: 'Open translation desk' }).click()
    const answer = 'Android lifecycle fixture 中文 العربية हिन्दी exact whitespace  '
    await page.locator('#translation-answer').fill(answer)
    await page.getByText('Draft saved on this device', { exact: false }).waitFor()
    report.renderer = await page.evaluate(() => ({ ua: navigator.userAgent, width: innerWidth, height: innerHeight, webgpu: !!navigator.gpu, platform: window.Capacitor.getPlatform() }))
    assert.equal(report.renderer.platform, 'android')
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await hideKeyboard()
    back()
    await page.getByRole('heading', { name: 'Translate with intention.' }).waitFor()
    await page.getByRole('button', { name: 'Continue translation' }).click()
    assert.equal(await page.locator('#translation-answer').inputValue(), answer)
    pass('Android hardware Back returns home and preserves the exact draft')
    adb('shell', 'settings', 'put', 'system', 'accelerometer_rotation', '0')
    adb('shell', 'settings', 'put', 'system', 'user_rotation', '1')
    await page.waitForFunction(() => innerWidth > innerHeight)
    assert.equal(await page.locator('#translation-answer').inputValue(), answer)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    adb('shell', 'settings', 'put', 'system', 'user_rotation', '0')
    await page.waitForFunction(() => innerHeight > innerWidth)
    pass('Portrait and landscape rotation retain the editor without overflow')
    adb('shell', 'input', 'keyevent', '3')
    adb('shell', 'am', 'start', '-n', `${app}/.MainActivity`)
    assert.equal(await page.locator('#translation-answer').inputValue(), answer)
    await browser.close()
    adb('shell', 'am', 'force-stop', app)
    adb('shell', 'am', 'start', '-W', '-n', `${app}/.MainActivity`)
    await connect()
    await page.getByRole('button', { name: 'Continue translation' }).click()
    assert.equal(await page.locator('#translation-answer').inputValue(), answer)
    pass('Background/foreground and process relaunch restore exact IndexedDB data')
    await nav('Home')
    await page.getByRole('button', { name: /Interpreting Listen/ }).click()
    await page.locator('#interpreting-mode').selectOption('simultaneous')
    await page.getByRole('button', { name: 'Open interpreting desk' }).click()
    await page.getByRole('button', { name: 'Start recording' }).click()
    await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(button => button.textContent.trim() === 'Stop and save')?.disabled)
    await page.waitForTimeout(1800)
    await page.getByRole('button', { name: 'Stop and save' }).click()
    await page.getByRole('button', { name: 'Save self-review without a score' }).click()
    await nav('Progress')
    await page.getByRole('button', { name: /Interpreting/ }).first().click()
    await page.getByRole('button', { name: 'Open saved self-review' }).first().click()
    const replay = page.locator('.interpreting-alignment audio[src^="blob:"]').first()
    await replay.waitFor()
    await replay.evaluate(audio => audio.play())
    await page.waitForFunction(() => [...document.querySelectorAll('audio[src^="blob:"]')].some(audio => audio.currentTime > 0))
    pass('Emulator microphone records, saves a scoreless review, and replays the stored codec')
    await nav('Settings')
    await page.getByRole('button', { name: 'Export local JSON', exact: true }).click()
    adb('shell', 'uiautomator', 'dump', '/sdcard/lingo-picker.xml')
    const xml = adb('shell', 'cat', '/sdcard/lingo-picker.xml')
    assert.ok(xml.includes('com.google.android.documentsui'))
    const save = xml.match(/<node[^>]*resource-id="android:id\/button1"[^>]*bounds="\[(\d+),(\d+)\]\[(\d+),(\d+)\]"/)
    assert.ok(save, 'System document picker Save control exists')
    adb('shell', 'input', 'tap', String(Math.floor((+save[1] + +save[3]) / 2)), String(Math.floor((+save[2] + +save[4]) / 2)))
    await page.getByText('A JSON export containing only local records is ready.', { exact: true }).waitFor()
    const remote = adb('shell', 'find', '/sdcard/Download', '-name', 'lingo-practice-*.json').split('\n').at(-1).trim()
    assert.ok(remote.endsWith('.json'))
    const exportPath = path.join(output, 'android-export.json')
    adb('pull', remote, exportPath)
    const exported = JSON.parse(fs.readFileSync(exportPath, 'utf8'))
    assert.equal(exported.writtenDraft.answer, answer)
    assert.ok(exported.recordings.some(record => record.byteLength > 0))
    report.codecs = [...new Set(exported.recordings.map(record => record.mimeType))]
    pass('Native document picker writes readable JSON with the exact draft and saved audio')
    await page.locator('#interface-language').selectOption('zh-CN')
    await page.getByRole('heading', { name: '清楚了解数据边界。' }).waitFor()
    await page.screenshot({ path: path.join(output, 'android-settings-chinese.png'), fullPage: true })
    assert.deepEqual(report.errors, [])
    assert.deepEqual(report.posts, [])
    pass('Chinese Android settings render with no uncaught errors or content POSTs')
  } catch (error) {
    report.failure = error.message
    console.error(error)
    if (page) report.visibleFailure = await page.locator('body').innerText().catch(() => '')
    process.exitCode = 1
  } finally {
    adb('shell', 'settings', 'put', 'system', 'user_rotation', '0')
    fs.writeFileSync(path.join(output, 'android-results.json'), JSON.stringify(report, null, 2))
    await browser?.close().catch(() => {})
  }
})()
