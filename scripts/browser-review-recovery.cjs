const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require('playwright-core')
const report = { checks: [], errors: [] }
;(async () => {
  const browser = await chromium.launch({ channel: process.env.QA_BROWSER_CHANNEL || (process.platform === 'win32' ? 'chrome' : undefined) })
  try {
    const context = await browser.newContext()
    const page = await context.newPage()
    const largeAssets = new Set(fs.readdirSync('dist/assets').filter(name => name.endsWith('.js') && fs.statSync(`dist/assets/${name}`).size > 1_000_000))
    const startupRuntimeRequests = []
    page.on('request', request => { if (largeAssets.has(new URL(request.url()).pathname.split('/').pop())) startupRuntimeRequests.push(request.url()) })
    page.on('pageerror', error => report.errors.push(error.message))
    const nav = name => page.getByRole('navigation').filter({ visible: true }).getByRole('button', { name, exact: true }).click()
    await page.goto('http://127.0.0.1:4178')
    await nav('Exam')
    await page.waitForFunction(() => [...document.querySelectorAll('.capability-status__badge')].some(element => element.textContent !== 'Checking this device'))
    assert.deepEqual(startupRuntimeRequests, [])
    report.checks.push('First-launch capability checks and navigation do not request the optional multi-megabyte AI runtime')
    await page.getByRole('button', { name: 'Start Exam Simulation', exact: true }).first().click()
    await page.locator('#exam-answer-input').fill('Synthetic recoverable exam answer')
    await page.evaluate(() => {
      window.qaRejectResumable = true
      const original = IDBObjectStore.prototype.put
      IDBObjectStore.prototype.put = function (value, ...args) {
        if (window.qaRejectResumable && this.name === 'examRuns' && !value.evaluationPausedAt) throw new DOMException('Synthetic resumable write rejection', 'QuotaExceededError')
        return original.call(this, value, ...args)
      }
    })
    await page.getByRole('button', { name: 'Submit Exam', exact: true }).click()
    await page.getByRole('button', { name: 'Yes, Submit Now →', exact: true }).click()
    await page.getByText(/resume state could not be saved/).first().waitFor()
    assert.equal(await page.locator('#exam-answer-input').inputValue(), 'Synthetic recoverable exam answer')
    await page.evaluate(() => { window.qaRejectResumable = false })
    await page.getByRole('button', { name: 'Save & Exit', exact: true }).click()
    await page.getByRole('button', { name: /Resume Exam \(/ }).waitFor()
    report.checks.push('Evaluation plus resumable-save failure leaves exact answer and a working Save & Exit retry')
    await nav('Settings')
    await page.getByRole('combobox', { name: 'Theme', exact: true }).selectOption('dark')
    await page.evaluate(() => {
      window.qaRejectPreferenceReset = true
      const original = Storage.prototype.removeItem
      Storage.prototype.removeItem = function (key) { if (window.qaRejectPreferenceReset && key === 'lingo-workspace-preferences-v1') throw new Error('Synthetic workspace reset rejection'); return original.call(this, key) }
    })
    await page.getByRole('button', { name: 'Delete local data', exact: true }).click()
    await page.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
    await page.getByText('Practice records were deleted, but workspace preferences could not be reset. Retry Delete local data in Settings.', { exact: true }).first().waitFor()
    assert.equal(await page.getByRole('dialog').count(), 1)
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('lingo-workspace-preferences-v1')).theme), 'dark')
    await page.evaluate(() => { window.qaRejectPreferenceReset = false })
    await page.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
    await page.getByRole('heading', { name: 'Translate with intention.' }).waitFor()
    assert.equal(await page.evaluate(() => localStorage.getItem('lingo-workspace-preferences-v1')), null)
    report.checks.push('Preference-reset failure is visible after practice deletion and explicit deletion retry clears the preferences')
    await nav('Home')
    await page.evaluate(() => window.dispatchEvent(new StorageEvent('storage', { key: 'lingo-practice-data-cleared-v1', newValue: 'active:synthetic-other-tab' })))
    await page.getByText(/reload it before saving new work/).waitFor()
    await page.getByRole('button', { name: /Interpreting Listen/ }).click()
    const start = page.getByRole('button', { name: 'Open interpreting desk' })
    await start.waitFor()
    await start.click()
    assert.equal(await page.locator('.interpreting-workspace').count(), 0)
    report.checks.push('A remotely cleared tab refuses to start an unsavable interpreting workspace')
    await context.close()
    const evaluatingContext = await browser.newContext()
    const evaluating = await evaluatingContext.newPage()
    evaluating.on('pageerror', error => report.errors.push(error.message))
    const evaluationNav = name => evaluating.getByRole('navigation').filter({ visible: true }).getByRole('button', { name, exact: true }).click()
    let releaseResponse, posts = 0
    const responseGate = new Promise(resolve => { releaseResponse = resolve })
    await evaluating.route('http://127.0.0.1:4555/**', async route => {
      posts++
      await responseGate
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ choices: [{ message: { content: JSON.stringify({ summary: 'Synthetic exam feedback', dimensions: { accuracy: 80, terminology: 80, grammar: 80, fluency: 80, taskStyle: 80 }, strengths: [], issues: [], alternatives: [], uncertainty: 'Synthetic fixture' }) } }] }) })
    })
    await evaluating.goto('http://127.0.0.1:4178')
    await evaluationNav('Settings')
    await evaluating.getByRole('radio', { name: /Local-first with cloud fallback/ }).check()
    await evaluating.locator('#cloud-base-url').fill('http://127.0.0.1:4555/v1')
    await evaluating.locator('#cloud-model').fill('synthetic-evaluator')
    await evaluating.locator('#cloud-api-key').fill('synthetic-session-key')
    await evaluating.getByRole('button', { name: 'Save endpoint preference', exact: true }).click()
    await evaluating.getByText('Cloud endpoint preference saved locally. The key was not saved.', { exact: true }).waitFor()
    await evaluationNav('Exam')
    await evaluating.getByRole('button', { name: 'Start Exam Simulation', exact: true }).first().click()
    await evaluating.locator('#exam-answer-input').fill('Synthetic exam answer')
    await evaluating.getByRole('button', { name: 'Submit Exam', exact: true }).click()
    await evaluating.getByRole('button', { name: 'Yes, Submit Now →', exact: true }).click()
    await evaluating.getByRole('dialog', { name: 'Send this task to the cloud?' }).getByRole('button', { name: 'Consent and evaluate' }).click()
    const progress = evaluating.getByRole('dialog', { name: 'Evaluating Exam Submissions…' })
    await progress.waitFor()
    assert.equal(await evaluating.getByRole('dialog').count(), 1)
    assert.ok(await progress.evaluate(element => element.contains(document.activeElement)))
    assert.equal(await progress.getByRole('status').getAttribute('aria-live'), 'polite')
    await evaluating.keyboard.press('Tab')
    assert.ok(await progress.evaluate(element => element.contains(document.activeElement)))
    await evaluating.keyboard.press('Escape')
    assert.equal(await progress.isVisible(), true)
    const { default: AxeBuilder } = require('@axe-core/playwright')
    const scan = await new AxeBuilder({ page: evaluating }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
    assert.deepEqual(scan.violations, [])
    releaseResponse()
    await evaluating.locator('.exam-results-page').waitFor()
    assert.equal(posts, 1)
    report.checks.push('Exam evaluation has one focused, keyboard-contained modal, polite progress, zero axe violations and one consented mocked POST')
    await evaluatingContext.close()
    assert.deepEqual(report.errors, [])
    report.checks.forEach(check => console.log('PASS', check))
  } catch (error) { report.failure = error.message; console.error(error); process.exitCode = 1 }
  finally { fs.mkdirSync('.browser-qa', { recursive: true }); fs.writeFileSync('.browser-qa/review-recovery-results.json', JSON.stringify(report, null, 2)); await browser.close() }
})()
