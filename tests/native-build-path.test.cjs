const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { setAndroidStartPath } = require('../scripts/prepare-native-assets.cjs')

test('Android upgrades bypass stale HTML while preserving the storage origin and existing config', async context => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'lingo-native-path-'))
  context.after(() => fs.rm(directory, { recursive: true, force: true }))
  const config = path.join(directory, 'capacitor.config.json'), index = path.join(directory, 'index.html')
  await fs.writeFile(config, JSON.stringify({ appId: 'qa', server: { hostname: 'localhost' } }))
  await fs.writeFile(index, '<script src="first.js"></script>')
  await setAndroidStartPath(config, index)
  const first = JSON.parse(await fs.readFile(config, 'utf8'))
  await setAndroidStartPath(config, index)
  assert.deepEqual(JSON.parse(await fs.readFile(config, 'utf8')), first)
  await fs.writeFile(index, '<script src="second.js"></script>')
  await setAndroidStartPath(config, index)
  const second = JSON.parse(await fs.readFile(config, 'utf8'))
  assert.notEqual(first.server.appStartPath, second.server.appStartPath)
  assert.equal(new URL(`https://localhost${second.server.appStartPath}`).origin, 'https://localhost')
  assert.equal(second.server.hostname, 'localhost')
  assert.equal(second.appId, 'qa')
})
